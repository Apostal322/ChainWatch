"""Generated results report (tables + per-time-step figure) from evaluated runs.

Numbers in ``reports/`` are produced by this module from ``test_metrics.json`` files,
never typed by hand.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from chainwatch.data import schema as S

MODEL_COLORS = {"xgboost": "#2a78d6", "logreg": "#eb6834"}  # validated categorical slots 1, 2
INK, INK_MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"

HEADLINE_COLS = [
    "model",
    "features",
    "AP (PR-AUC)",
    "ROC-AUC",
    "precision",
    "recall",
    "F1",
    "threshold",
    "P@100",
    "P@500",
    "R@500",
]


def per_step_frame(table: pd.DataFrame, artifacts_dir: Path) -> pd.DataFrame:
    frames = []
    for _, row in table.iterrows():
        df = pd.read_csv(artifacts_dir / row["run"] / "test_per_time_step.csv")
        frames.append(df.assign(model=row["model"], features=row["features"]))
    return pd.concat(frames, ignore_index=True)


def plot_per_step_ap(per_step: pd.DataFrame, feature_set: str, path: Path) -> None:
    sub = per_step[per_step["features"] == feature_set]
    fig, ax = plt.subplots(figsize=(10, 4), facecolor=SURFACE)
    for model, g in sub.groupby("model"):
        g = g.sort_values(S.TIME_STEP)
        ax.plot(
            g[S.TIME_STEP],
            g["average_precision"],
            color=MODEL_COLORS.get(model, INK),
            lw=2,
            marker="o",
            ms=5,
            label=model,
        )
        last = g.iloc[-1]
        ax.annotate(
            model,
            (last[S.TIME_STEP], last["average_precision"]),
            xytext=(6, 0),
            textcoords="offset points",
            va="center",
            fontsize=9,
            color=INK_MUTED,
        )
    counts = sub.drop_duplicates(S.TIME_STEP).sort_values(S.TIME_STEP)
    for _, r in counts.iterrows():
        ax.text(
            r[S.TIME_STEP],
            -0.13,
            str(int(r["n_illicit"])),
            ha="center",
            fontsize=7,
            color=INK_MUTED,
            transform=ax.get_xaxis_transform(),
        )
    ax.text(
        0.0, -0.2, "illicit count per step", transform=ax.transAxes, fontsize=7, color=INK_MUTED
    )
    ax.set_title(
        f"Test average precision per time step (features: {feature_set})",
        loc="left",
        fontsize=11,
        color=INK,
        pad=12,
    )
    ax.set_ylabel("average precision", color=INK_MUTED)
    ax.set_ylim(0, 1.02)
    ax.set_xticks(counts[S.TIME_STEP])
    ax.set_facecolor(SURFACE)
    ax.grid(axis="y", color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_MUTED, labelsize=8)
    ax.legend(frameon=False, loc="upper right", labelcolor=INK_MUTED)
    fig.tight_layout()
    fig.subplots_adjust(bottom=0.22)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def write_report(table: pd.DataFrame, artifacts_dir: Path, reports_dir: Path) -> Path:
    per_step = per_step_frame(table, artifacts_dir)
    per_step.to_csv(reports_dir / "baseline_per_time_step.csv", index=False)
    feature_sets = list(dict.fromkeys(table["features"]))
    for fs in feature_sets:
        plot_per_step_ap(per_step, fs, reports_dir / "figures" / f"per_step_ap_{fs}.png")

    def md(df: pd.DataFrame) -> str:
        return df.to_markdown(index=False, floatfmt=".4f")

    lat = table[["model", "features", "latency p50 (ms/row)", "batch (us/tx)"]]
    k = next(c for c in table.columns if c.startswith("mean per-step P@"))
    wide = per_step.pivot_table(
        index=S.TIME_STEP, columns=["model", "features"], values="average_precision"
    )
    wide.columns = [f"{m}/{f}" for m, f in wide.columns]
    n_ill = per_step.drop_duplicates(S.TIME_STEP).set_index(S.TIME_STEP)["n_illicit"]
    wide.insert(0, "n_illicit", n_ill.astype(str))
    wide.index = wide.index.astype(str)

    lines = [
        "# Phase 1 baseline results (generated)",
        "",
        "Generated by `chainwatch report` from `artifacts/runs/*/test_metrics.json`.",
        "Test split = time steps 35-49 (labelled transactions only). Thresholds were chosen",
        "on validation (steps 30-34). See docs/EVALUATION.md for the protocol.",
        "",
        "## Pooled test metrics",
        "",
        md(table[HEADLINE_COLS]),
        "",
        f"## Investigation-budget view ({k.removeprefix('mean ')}, averaged over test steps)",
        "",
        md(table[["model", "features", k]]),
        "",
        "## Per-time-step average precision (test)",
        "",
        wide.reset_index().to_markdown(index=False, floatfmt=".3f"),
        "",
        *[f"![per-step AP {fs}](figures/per_step_ap_{fs}.png)\n" for fs in feature_sets],
        "## In-process inference latency",
        "",
        "CPU, single process, model + preprocessing only; for relative comparison.",
        "",
        md(lat),
        "",
    ]
    out = reports_dir / "baseline_results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out
